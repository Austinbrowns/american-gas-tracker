"""Daily Issue body generation and optional GitHub Issue publishing."""

from __future__ import annotations

import json
from typing import Any
from urllib.error import HTTPError
from urllib.request import Request, urlopen


def _money(value: float) -> str:
    return f"${value:.4f}"


def build_issue_body(
    date: str,
    moves: list[dict[str, Any]],
    new_items: list[str],
    gone_items: list[str],
    source_results: list[dict[str, Any]],
) -> str:
    lines = [
        f"## American Gas Price Report — {date}",
        "",
        "Movement is ranked by the largest absolute percentage change among regular, mid-grade, premium, and diesel prices for each state.",
        "",
        "### Sources",
    ]
    for source in source_results:
        status = "✅ OK" if source.get("ok") else "❌ Failed"
        detail = f" ({source.get('error')})" if source.get("error") else ""
        lines.append(f"- {source['name']}: {status}; {source.get('count', 0)} items{detail}")

    lines.extend(["", "### Biggest moves"])
    if moves:
        lines.append("| State | Field | Old | New | Difference | Score |")
        lines.append("|---|---|---:|---:|---:|---:|")
        for move in moves[:10]:
            direction = "+" if move["difference"] >= 0 else ""
            lines.append(
                f"| {move['item']} | {move['column']} | {_money(move['old'])} | {_money(move['new'])} | "
                f"{direction}{move['difference']:.4f} | {move['score']:.2f}% |"
            )
    else:
        lines.append("No comparable item changed since the previous available run.")

    lines.extend(["", "### Appeared or disappeared"])
    lines.append(f"- Appeared: {', '.join(new_items) if new_items else 'None'}")
    lines.append(f"- Disappeared: {', '.join(gone_items) if gone_items else 'None'}")
    lines.extend(["", "Generated by the gas-price-tracker GitHub Actions pipeline."])
    return "\n".join(lines) + "\n"


def _request(url: str, token: str, method: str = "GET", payload: dict[str, Any] | None = None) -> Any:
    body = json.dumps(payload).encode("utf-8") if payload is not None else None
    request = Request(
        url,
        data=body,
        method=method,
        headers={
            "Accept": "application/vnd.github+json",
            "Authorization": f"Bearer {token}",
            "X-GitHub-Api-Version": "2022-11-28",
            "Content-Type": "application/json",
            "User-Agent": "gas-price-tracker",
        },
    )
    with urlopen(request, timeout=30) as response:
        content = response.read()
        return json.loads(content) if content else None


def publish_daily_issue(date: str, body: str, token: str | None, repository: str | None) -> str:
    """Create/update today's issue and close older tracker issues.

    Local runs without GitHub credentials intentionally skip the network call.
    """

    if not token or not repository:
        return "skipped: GITHUB_TOKEN or GITHUB_REPOSITORY is not set"

    base = f"https://api.github.com/repos/{repository}"
    title = f"{date} — Gas Price Daily Report"
    issues = _request(f"{base}/issues?state=open&per_page=100", token)
    current: dict[str, Any] | None = None
    for issue in issues or []:
        if "pull_request" in issue or "Gas Price Daily Report" not in issue.get("title", ""):
            continue
        if issue.get("title") == title:
            current = issue
        else:
            try:
                _request(f"{base}/issues/{issue['number']}", token, "PATCH", {"state": "closed"})
            except HTTPError:
                pass

    if current:
        _request(f"{base}/issues/{current['number']}", token, "PATCH", {"title": title, "body": body, "state": "open"})
        return f"updated issue #{current['number']}"
    created = _request(f"{base}/issues", token, "POST", {"title": title, "body": body})
    return f"created issue #{created['number']}"

